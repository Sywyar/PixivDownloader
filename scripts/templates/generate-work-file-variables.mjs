import {readFileSync, writeFileSync, mkdirSync} from 'node:fs';
import assert from 'node:assert/strict';
import {parse} from '../i18n/lib/properties-parser.mjs';

const root = new URL('../../', import.meta.url);
const variables = JSON.parse(readFileSync(new URL('work-file-variables.json', import.meta.url), 'utf8'));
const seen = new Set();
for (const variable of variables) {
    for (const field of ['id', 'token', 'label']) assert.match(variable[field], /^[A-Za-z][A-Za-z0-9_+-]*$/);
    assert.match(variable.token, /^(?:[a-z][a-z0-9]*(?:_[a-z0-9]+)*|ai\+|R18\+?)$/);
    for (const field of ['numeric', 'download', 'importing', 'directory', 'directoryOptional']) assert.equal(typeof variable[field], 'boolean');
    const key = variable.token.replaceAll('_', '').toLowerCase();
    assert(!seen.has(key), 'Duplicate template variable: ' + key);
    assert.equal(variable.id.replaceAll('_', '').toLowerCase(), key);
    assert(variable.download || variable.importing || variable.directory);
    assert(!variable.directoryOptional || variable.directory);
    seen.add(key);
}
const java = `// Generated by scripts/templates/generate-work-file-variables.mjs.
package top.sywyar.pixivdownload.core.work.filename;

import java.util.List;
import java.util.Map;
import java.util.function.Function;
import java.util.stream.Collectors;

/** 下载命名与本地路径解析共用的变量定义；求值仍由各自场景负责。 */
public final class WorkTemplateVariables {
    private WorkTemplateVariables() {}

    /**
     * 变量的稳定身份、拼写及适用场景。
     * @param id 解析结果中的身份
     * @param token 模板中的标准拼写，不含花括号
     * @param label 由界面所属命名空间解析的说明键后缀
     * @param numeric 是否只包含十进制数字
     * @param download 是否支持下载命名
     * @param importing 是否支持本地反向解析
     * @param directory 是否支持最终作品目录
     * @param directoryOptional 是否允许目录变量为空
     */
    public record Variable(String id, String token, String label, boolean numeric, boolean download, boolean importing, boolean directory, boolean directoryOptional) {}

    private static final List<Variable> VARIABLES = List.of(
${variables.map(v => '            new Variable(' + [v.id, v.token, v.label, v.numeric, v.download, v.importing, v.directory, v.directoryOptional].map(value => JSON.stringify(value)).join(', ') + ')').join(',\n')});
    private static final Map<String, Variable> BY_NAME = VARIABLES.stream()
            .collect(Collectors.toUnmodifiableMap(Variable::token, Function.identity()));

    /** @return 不可变的全部变量定义 */
    public static List<Variable> all() { return VARIABLES; }

    /**
     * 按标准拼写查询本地导入变量。
     * @param name 不含花括号的变量名
     * @return 可反向解析的变量；未知或不适用于导入时返回 null
     */
    public static Variable forImport(String name) {
        Variable variable = find(name);
        return variable != null && variable.importing() ? variable : null;
    }

    /**
     * 精确匹配模板的标准拼写，不接受驼峰或大小写变体。
     * @param name 不含花括号的变量名
     * @return 已知变量；未知时返回 null
     */
    public static Variable find(String name) { return BY_NAME.get(name); }

    /** @return 本地导入界面展示的变量列表 */
    public static String importTokens() {
        return VARIABLES.stream().filter(Variable::importing).map(v -> "{" + v.token() + "}")
                .collect(Collectors.joining(", "));
    }

}
`;
const js = `// BEGIN GENERATED WORK FILE VARIABLES
// Generated by scripts/templates/generate-work-file-variables.mjs.
const WORK_FILE_VARIABLES = Object.freeze(${JSON.stringify(variables, null, 4)}.map(Object.freeze));
// END GENERATED WORK FILE VARIABLES`;
const javaPath = 'pixivdownload-core-api/src/main/java/top/sywyar/pixivdownload/core/work/filename/WorkTemplateVariables.java';
const jsPath = 'pixivdownload-plugin-download-workbench/src/main/resources/static/pixiv-batch/filename-template.js';
const current = readFileSync(new URL(jsPath, root), 'utf8').replaceAll('\r\n', '\n');
const marker = /\/\/ BEGIN GENERATED WORK FILE VARIABLES[\s\S]*?\/\/ END GENERATED WORK FILE VARIABLES/;
const updated = marker.test(current) ? current.replace(marker, () => js) : current.replace("'use strict';", "'use strict';\n" + js);
const webRoot = 'pixivdownload-plugin-download-workbench/src/main/resources/';
const bundle = parse(readFileSync(new URL(webRoot + 'i18n/web/batch.properties', root), 'utf8'));
assert.deepEqual(bundle.errors, []);
const labels = new Map(bundle.entries.map(entry => [entry.key, entry.value]));
const escape = text => text.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;');
const help = variables.filter(v => v.download).map(v => {
    const key = 'filename.var.' + v.label;
    assert(labels.has(key), 'Missing variable label: ' + key);
    return '                            <div><code>{' + v.token + '}</code> <span data-i18n="' + key + '">' + escape(labels.get(key)) + '</span></div>';
}).join('\n');
const htmlPath = webRoot + 'static/pixiv-batch.html';
const html = readFileSync(new URL(htmlPath, root), 'utf8').replaceAll('\r\n', '\n');
const grid = /(<div class="filename-token-grid">\n)[\s\S]*?(\n                        <\/div>)/;
assert(grid.test(html), 'Missing filename variable help');
const updatedHtml = html.replace(grid, (_, open, close) => open + help + close);
for (const [path, content] of [[javaPath, java], [jsPath, updated], [htmlPath, updatedHtml]]) {
    const url = new URL(path, root);
    if (process.argv.includes('--check')) assert.equal(readFileSync(url, 'utf8').replaceAll('\r\n', '\n'), content, path + ' is stale');
    else { mkdirSync(new URL('.', url), {recursive: true}); writeFileSync(url, content, 'utf8'); }
}
