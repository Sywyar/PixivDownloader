import {readFileSync, writeFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';

const root = new URL('../../', import.meta.url);
const tokens = JSON.parse(readFileSync(new URL('experience-tokens.json', import.meta.url), 'utf8'));
const palettes = Object.entries(tokens).filter(([name]) => name !== 'reference');
const luminance = hex => hex.slice(1).match(/../g).map(value => parseInt(value, 16) / 255)
    .map(value => value <= 0.04045 ? value / 12.92 : ((value + 0.055) / 1.055) ** 2.4)
    .reduce((sum, value, index) => sum + value * [0.2126, 0.7152, 0.0722][index], 0);
const contrast = (a, b) => (Math.max(luminance(a), luminance(b)) + 0.05)
    / (Math.min(luminance(a), luminance(b)) + 0.05);

for (const [name, palette] of palettes) {
    for (const foreground of ['text', 'secondaryText', 'link', 'success', 'warning', 'error']) {
        for (const background of ['background', 'surface', 'secondarySurface']) {
            assert(contrast(palette[foreground], palette[background]) >= 4.5, `${name}: ${foreground}/${background}`);
        }
    }
    for (const role of ['success', 'warning', 'error']) {
        assert(contrast(palette[role], palette[role + 'Surface']) >= 4.5, `${name}: ${role}`);
    }
    assert(contrast(palette.onAccent, palette.accent) >= 4.5, `${name}: button text`);
    assert(contrast(palette.text, palette.selection) >= 4.5, `${name}: selection`);
    assert(contrast(palette.controlBorder, palette.surface) >= 3, `${name}: control boundary`);
}

const cssProperties = palette => Object.entries(palette).map(([name, value]) => `    --exp-${name.replace(/[A-Z]/g, c => '-' + c.toLowerCase())}: ${value};`).join('\n');
const css = `/* Generated by scripts/design/generate-experience-tokens.mjs. */
:root.ab-workbench {\n${cssProperties(tokens.light)}\n}
:root.ab-workbench[data-theme="dark"] {\n${cssProperties(tokens.dark)}\n}
@media (prefers-contrast: more) {
  :root.ab-workbench {\n${cssProperties(tokens.highContrastLight)}\n  }
  :root.ab-workbench[data-theme="dark"] {\n${cssProperties(tokens.highContrastDark)}\n  }
}
`;
const kotlin = `// Generated by scripts/design/generate-experience-tokens.mjs.
package top.sywyar.pixivdownload.guicompose

import androidx.compose.ui.graphics.Color

internal data class ExperiencePalette(
${Object.keys(tokens.light).map(name => `    val ${name}: Color,`).join('\n')}
)

internal object ExperienceTokens {
${palettes.map(([name, palette]) => `    val ${name} = ExperiencePalette(\n${Object.entries(palette).map(([key, value]) => `        ${key} = Color(0xFF${value.slice(1).toUpperCase()}),`).join('\n')}\n    )`).join('\n')}
}
`;
const splashColors = `// Generated by scripts/design/generate-experience-tokens.mjs.
package top.sywyar.pixivdownload.gui.bootstrap;

record StartupSplashColors(int surface, int text, int secondaryText, int accent, int border) {
${palettes.map(([name, palette]) => `    private static final StartupSplashColors ${name} = new StartupSplashColors(${['surface', 'text', 'secondaryText', 'accent', 'controlBorder'].map(key => `0x${palette[key].slice(1).toUpperCase()}`).join(', ')});`).join('\n')}

    static StartupSplashColors forAppearance(StartupAppearance appearance) {
        return appearance.highContrast()
                ? (appearance.dark() ? highContrastDark : highContrastLight)
                : (appearance.dark() ? dark : light);
    }
}
`;
for (const [path, content] of [
    ['pixivdownload-app/src/main/java/top/sywyar/pixivdownload/gui/bootstrap/StartupSplashColors.java', splashColors],
    ['pixivdownload-plugin-download-workbench/src/main/resources/static/pixiv-batch-alt/experience-tokens.css', css],
    ['pixivdownload-plugin-gui-compose/src/main/kotlin/top/sywyar/pixivdownload/guicompose/ExperienceTokens.kt', kotlin],
]) {
    const url = new URL(path, root);
    if (process.argv.includes('--check')) assert.equal(readFileSync(url, 'utf8'), content, `${path} is stale`);
    else writeFileSync(url, content, 'utf8');
    console.log(`${process.argv.includes('--check') ? 'Verified' : 'Generated'} ${fileURLToPath(url)}`);
}
console.log('Four opaque palettes: text >= 4.5:1, control boundaries >= 3:1.');
